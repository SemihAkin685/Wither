//! The script API as completion needs it: what each public module exports and what members
//! every declared type has. It is generated from the game's script module metadata with
//! bedrock_addon's reader (`cargo run -p wither-completion --example script_api`) and shipped
//! as data, the metadata itself is tens of megabytes and only comes with a dedicated server.

use std::sync::OnceLock;

use bedrock_addon::families::script::meta::model::script::{
    Argument, ClassConstant, ConstValue, Function, Property, RawTypeDesc,
};
use bedrock_addon::families::script::meta::NativeModule;
use serde::{Deserialize, Serialize};

const DATA: &str = include_str!("../data/script_api.json");

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ScriptModuleApi {
    /// The name packs import, `@minecraft/server`.
    pub name: String,
    pub version: String,
    pub exports: Vec<ScriptExport>,
    pub types: Vec<ScriptType>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ScriptExport {
    pub name: String,
    /// class, interface, enum, error, object, function or constant.
    pub kind: String,
    /// Shown next to the name, a type or a signature.
    pub detail: String,
    /// The declared type an object export holds (`World` for `world`), for member lookups.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub type_name: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ScriptType {
    pub name: String,
    pub kind: String,
    /// Types whose members this one inherits.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub bases: Vec<String>,
    pub members: Vec<ScriptMember>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ScriptMember {
    pub name: String,
    /// method, property or constant.
    pub kind: String,
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub is_static: bool,
    pub detail: String,
    /// The declared type the member gives back, so `world.afterEvents.` can go on.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub returns: Option<String>,
    /// `returns` is the element type of an array, like `Player` for `getPlayers()`.
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub many: bool,
    /// For a method taking a callback, the declared types the callback is called with. This is
    /// what types `event` in `signal.subscribe((event) => ...)`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub callback: Option<Vec<Option<String>>>,
}

/// The shipped script API, read once.
pub fn script_api() -> &'static [ScriptModuleApi] {
    static API: OnceLock<Vec<ScriptModuleApi>> = OnceLock::new();
    // the data is generated by this crate, a parse failure is a broken build, not user input
    API.get_or_init(|| serde_json::from_str(DATA).expect("data/script_api.json is valid"))
}

/// Turns one declaring module into the completion shape. `name` and `version` are the public
/// module's, the declarations may come from its bindings module.
pub fn module_api(name: &str, version: &str, declared: &NativeModule) -> ScriptModuleApi {
    let mut exports = Vec::new();
    let mut types = Vec::new();
    for class in &declared.classes {
        exports.push(export(&class.name, "class", String::new(), None));
        let mut members: Vec<ScriptMember> = class.functions.iter().map(method).collect();
        members.extend(class.properties.iter().map(property));
        members.extend(class.constants.iter().map(constant));
        types.push(declared_type(
            &class.name,
            "class",
            &class.base_types,
            members,
        ));
    }
    for interface in &declared.interfaces {
        exports.push(export(&interface.name, "interface", String::new(), None));
        let mut members: Vec<ScriptMember> = interface.properties.iter().map(property).collect();
        members.extend(interface.functions.iter().flatten().map(method));
        members.extend(interface.constants.iter().flatten().map(constant));
        types.push(declared_type(
            &interface.name,
            "interface",
            &interface.base_types,
            members,
        ));
    }
    for error in &declared.errors {
        exports.push(export(&error.name, "error", String::new(), None));
        let mut members: Vec<ScriptMember> = error.functions.iter().map(method).collect();
        members.extend(error.properties.iter().map(property));
        types.push(declared_type(&error.name, "error", &[], members));
    }
    for item in &declared.enums {
        exports.push(export(&item.name, "enum", String::new(), None));
        let members = item.constants.iter().map(constant).collect();
        types.push(declared_type(&item.name, "enum", &[], members));
    }
    for object in &declared.objects {
        exports.push(export(
            &object.name,
            "object",
            render(&object.ty),
            resolvable(&object.ty),
        ));
    }
    for function in &declared.functions {
        exports.push(export(
            &function.name,
            "function",
            signature(function),
            None,
        ));
    }
    for item in &declared.constants {
        exports.push(export(
            &item.name,
            "constant",
            value_text(&item.value),
            None,
        ));
    }
    exports.sort_by(|a, b| a.name.cmp(&b.name));
    types.sort_by(|a, b| a.name.cmp(&b.name));
    ScriptModuleApi {
        name: name.to_owned(),
        version: version.to_owned(),
        exports,
        types,
    }
}

fn export(name: &str, kind: &str, detail: String, type_name: Option<String>) -> ScriptExport {
    ScriptExport {
        name: name.to_owned(),
        kind: kind.to_owned(),
        detail,
        type_name,
    }
}

fn declared_type(
    name: &str,
    kind: &str,
    bases: &[RawTypeDesc],
    mut members: Vec<ScriptMember>,
) -> ScriptType {
    members.sort_by(|a, b| a.name.cmp(&b.name));
    ScriptType {
        name: name.to_owned(),
        kind: kind.to_owned(),
        bases: bases.iter().map(|base| base.name.clone()).collect(),
        members,
    }
}

fn method(function: &Function) -> ScriptMember {
    let callback = function
        .arguments
        .iter()
        .find_map(|argument| argument.ty.closure_type.as_ref())
        .map(|closure| closure.argument_types.iter().map(resolvable).collect());
    let (returns, many) = returned(&function.return_type);
    ScriptMember {
        name: function.name.clone(),
        kind: if function.is_constructor {
            "constructor"
        } else {
            "method"
        }
        .to_owned(),
        is_static: function.is_static.unwrap_or(false),
        detail: signature(function),
        returns,
        many,
        callback,
    }
}

fn property(property: &Property) -> ScriptMember {
    let detail = if property.is_read_only {
        format!("readonly {}", render(&property.ty))
    } else {
        render(&property.ty)
    };
    let (returns, many) = returned(&property.ty);
    ScriptMember {
        name: property.name.clone(),
        kind: "property".to_owned(),
        is_static: false,
        detail,
        returns,
        many,
        callback: None,
    }
}

fn constant(constant: &ClassConstant) -> ScriptMember {
    ScriptMember {
        name: constant.name.clone(),
        kind: "constant".to_owned(),
        is_static: constant.is_static,
        detail: value_text(&constant.value),
        returns: resolvable(&constant.ty),
        many: false,
        callback: None,
    }
}

fn value_text(value: &ConstValue) -> String {
    match value {
        ConstValue::Str(text) => format!("{text:?}"),
        ConstValue::Int(number) => number.to_string(),
    }
}

fn signature(function: &Function) -> String {
    let arguments: Vec<String> = function.arguments.iter().map(argument).collect();
    format!(
        "({}): {}",
        arguments.join(", "),
        render(&function.return_type)
    )
}

fn argument(argument: &Argument) -> String {
    let optional = argument.ty.name == "optional";
    let ty = match (&argument.ty.optional_type, optional) {
        (Some(inner), true) => render(inner),
        _ => render(&argument.ty),
    };
    format!("{}{}: {ty}", argument.name, if optional { "?" } else { "" })
}

/// The declared type a value of `ty` is, looking through optional, so member lookups can follow
/// it. Arrays, promises and primitives have no members we track.
fn resolvable(ty: &RawTypeDesc) -> Option<String> {
    match ty.name.as_str() {
        "optional" => ty.optional_type.as_deref().and_then(resolvable),
        _ if ty.is_bind_type => Some(ty.name.clone()),
        _ => None,
    }
}

/// Like [`resolvable`], and an array of a declared type gives its element with `true`.
fn returned(ty: &RawTypeDesc) -> (Option<String>, bool) {
    match ty.name.as_str() {
        "optional" => ty.optional_type.as_deref().map_or((None, false), returned),
        "array" => (ty.element_type.as_deref().and_then(resolvable), true),
        _ => (resolvable(ty), false),
    }
}

/// A type written the way TypeScript would, for the detail column.
fn render(ty: &RawTypeDesc) -> String {
    let inner = |payload: &Option<Box<RawTypeDesc>>| {
        payload
            .as_deref()
            .map_or_else(|| "unknown".to_owned(), render)
    };
    match ty.name.as_str() {
        "optional" => format!("{} | undefined", inner(&ty.optional_type)),
        "array" => format!("{}[]", inner(&ty.element_type)),
        "promise" => format!("Promise<{}>", inner(&ty.promise_type)),
        "map" => format!("Record<{}, {}>", inner(&ty.key_type), inner(&ty.value_type)),
        "variant" => ty
            .variant_types
            .iter()
            .flatten()
            .map(render)
            .collect::<Vec<_>>()
            .join(" | "),
        "closure" => match &ty.closure_type {
            Some(closure) => {
                let arguments: Vec<String> = closure
                    .argument_types
                    .iter()
                    .enumerate()
                    .map(|(i, arg)| format!("arg{i}: {}", render(arg)))
                    .collect();
                format!(
                    "({}) => {}",
                    arguments.join(", "),
                    render(&closure.return_type)
                )
            }
            None => "Function".to_owned(),
        },
        "int8" | "int16" | "int32" | "uint8" | "uint16" | "uint32" | "float" | "double" => {
            "number".to_owned()
        }
        "int64" | "uint64" => "bigint".to_owned(),
        _ => match (&ty.generic_base, &ty.generic_types) {
            (Some(base), Some(args)) => format!(
                "{}<{}>",
                render(base),
                args.iter().map(render).collect::<Vec<_>>().join(", ")
            ),
            _ => ty.name.clone(),
        },
    }
}
